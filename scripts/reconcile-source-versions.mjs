import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { gameData } from '../src/data/gameData.ts';
import { parsePokemonDatabaseHtml } from '../src/domain/qa/sourceCompare.ts';
import { reconcileEncounterWithSource } from '../src/domain/qa/sourceReconcile.ts';

const cacheDir = resolve('artifacts/qa/source-cache');
mkdirSync(cacheDir, { recursive: true });

function cachePath(url) {
  return resolve(cacheDir, `${Buffer.from(url).toString('base64url')}.html`);
}

function isExternalSource(source) {
  return typeof source === 'string' && /^https:\/\/pokemondb\.net\/location\//.test(source);
}

async function readSource(url) {
  const path = cachePath(url);
  if (existsSync(path)) return readFileSync(path, 'utf8');
  const response = await fetch(url, { headers: { 'user-agent': 'RouteDex-source-reconcile/1.0' } });
  if (!response.ok) throw new Error(`${response.status} ${response.statusText}`);
  const html = await response.text();
  writeFileSync(path, html, 'utf8');
  return html;
}

const urls = [...new Set(gameData.locations
  .flatMap((location) => location.encounters.map((encounter) => encounter.source))
  .filter(isExternalSource))];
const sources = new Map();
const fetchErrors = [];

for (const url of urls) {
  try {
    const records = parsePokemonDatabaseHtml(await readSource(url));
    if (!records.length) throw new Error('A fonte foi lida, mas nenhuma ocorrência foi reconhecida.');
    sources.set(url, records);
  } catch (error) {
    fetchErrors.push({ url, message: error instanceof Error ? error.message : String(error) });
  }
}

if (fetchErrors.length) {
  console.error(JSON.stringify({ command: 'reconcile-source-versions', error: 'Fontes incompletas; nenhum arquivo foi alterado.', fetchErrors }, null, 2));
  process.exitCode = 1;
} else {
  let comparedLocations = 0;
  let comparedEncounters = 0;
  let changedEncounters = 0;
  let removedDetails = 0;

  const reconciledData = {
    ...gameData,
    locations: gameData.locations.map((location) => {
      const url = location.encounters.find((encounter) => isExternalSource(encounter.source))?.source;
      if (!url) return location;
      comparedLocations += 1;
      const source = sources.get(url);
      return {
        ...location,
        encounters: location.encounters.map((encounter) => {
          const result = reconcileEncounterWithSource(encounter, source);
          comparedEncounters += 1;
          if (result.changed) changedEncounters += 1;
          removedDetails += result.removedDetails;
          return result.encounter;
        }),
      };
    }),
  };

  const output = `// Generated by scripts/import_workbook.py and scripts/reconcile-source-versions.mjs\nexport const gameData = ${JSON.stringify(reconciledData, null, 2)} as const;\n`;
  writeFileSync(resolve('src/data/gameData.ts'), output, 'utf8');
  console.log(JSON.stringify({
    command: 'reconcile-source-versions',
    sources: urls.length,
    comparedLocations,
    comparedEncounters,
    changedEncounters,
    removedDetails,
    output: 'src/data/gameData.ts',
  }, null, 2));
}
